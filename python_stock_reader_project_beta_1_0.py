class Trends(Analyze_Performance):
  def __init__(self, Ticker_symbol, start_date, end_date, data):
    super().__init__(Ticker_symbol, start_date, end_date, data)

  def Identify_Price_Action(self):
    self.data["Price_Action"] = ""

    for i in range(1,len(self.data)):
      if self.data["Close"].iloc[i] > self.data["Close"].iloc[i-1]:
        self.data.loc[self.data.index[i], "Price_Action"] = "Bullish"  # Fixed: use .loc
      elif self.data["Close"].iloc[i] < self.data['Close'].iloc[i-1]:
        self.data.loc[self.data.index[i], "Price_Action"] = "Bearish"  # Fixed: use .loc
      else:
        self.data.loc[self.data.index[i], "Price_Action"] = "Neutral"  # Fixed: use .loc

    return self.data

  def Buy_Sell_Signal(self):
    self.data['Signal Score'] = 0

    # Fixed: Use .loc for boolean indexing
    self.data.loc[self.data["SMA"] > self.data["EMA"], "Signal Score"] += 2
    self.data.loc[self.data["SMA"] < self.data["EMA"], "Signal Score"] -= 2

    self.data.loc[self.data["RSI"] < 30, "Signal Score"] += 3
    self.data.loc[self.data['RSI'] > 70, "Signal Score"] -= -3

    last_row = self.data.iloc[-1]
    second_last_row = self.data.iloc[-2]

    if second_last_row['MACD'] < second_last_row['Signal Line'] and last_row['MACD'] > last_row['Signal Line']:
       self.data.loc[self.data.index[-1], 'Signal Score'] += 2  # Fixed: use .loc
    elif second_last_row['MACD'] > second_last_row['Signal Line'] and last_row['MACD'] < last_row['Signal Line']:
       self.data.loc[self.data.index[-1], 'Signal Score'] -= 2  # Fixed: use .loc

    self.data['Signal'] = 0
    self.data.loc[self.data['Signal Score'] >= 4, 'Signal'] = 1  # Strong buy
    self.data.loc[self.data['Signal Score'] <= -4, 'Signal'] = -1  # Strong sell
    self.data.loc[abs(self.data['Signal Score']) < 4, 'Signal'] = 0 # Hold / Neutral

    print(self.data[['Date', 'Close', 'Signal']])
    return self.data




