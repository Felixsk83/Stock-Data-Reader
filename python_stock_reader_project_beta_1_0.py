  def Volatility_Calculation(self):
    V_Calculations = { "Squared Difference":[], "Volatility":[]}
    #Average Returns
    Average_Returns = sum(list(self.data["Daily_returns"])) / len(self.data["Daily_returns"])
    #print(Average_Returns)

    #Squared Difference
    for i in range(len(self.data["Date"])):
      if i <= 0:
        V_Calculations["Squared Difference"].append(0)
      else:
        Squared_Difference = (self.data["Daily_returns"].iloc[i] - Average_Returns) ** 2
        V_Calculations["Squared Difference"].append(Squared_Difference)
    #print(V_Calculations["Squared Difference"])

    #Variance
    for i in range(len(self.data["Date"])):
      Sum_of_Square_Difference= 0
