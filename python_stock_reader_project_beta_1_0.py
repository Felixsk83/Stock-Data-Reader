class Stock_Exchange_table:

  def __init__(self, Ticker_symbol, start_date, end_date,):
    self.Ticker_symbol = Ticker_symbol
    self.start_date = None
    self.end_date = None

    try:
      self.start_date = datetime.strptime(start_date, "%Y-%m-%d").date()
      self.end_date = datetime.strptime(end_date, "%Y-%m-%d").date()

      if self.start_date > self.end_date:
        raise ValueError("Start date must be before end date!")
      if self.end_date > date.today():
        raise ValueError("End data cannot be in the future!")

    except ValueError as VE:
      print(f"Error date: {VE}")


  def Stock_Exchange_data(self):
    if self.start_date is None or self.end_date is None:
      print("Cannot fetch data due to invalid setup!")
      return None

    try:
        data = yf.download(self.Ticker_symbol, self.start_date, self.end_date,interval="1d")

        if data.empty:
            raise ValueError(f"No data found for ticker '{self.Ticker_symbol}'. Please check the symbol.")

        if isinstance(data.columns, pd.MultiIndex):
            data.columns = data.columns.get_level_values(0)

        data_with_date_column = data.reset_index()
        return data_with_date_column

    except Exception as e:
        print(f"Error fetching data for {self.Ticker_symbol}: {e}")

